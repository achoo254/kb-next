const ADMIN_TEXT: Record<Locale, Record<AdminMessageKey, string>> = { vi: adminVi, en: adminEn };

export function useAdminText(): { t: ScreenTranslate<AdminMessageKey>; locale: Locale } {
  return useScreenText(ADMIN_TEXT);
}

/** dd/mm/yyyy in Saigon time (A02 "Ngày đăng", A03 "Tạo 02/11/2026"). */
export function dayText(iso: string): string {
  const parts = new Intl.DateTimeFormat('en-GB', { day: '2-digit', month: '2-digit', year: 'numeric', timeZone: 'Asia/Ho_Chi_Minh' }).formatToParts(new Date(iso));
  const part = (type: 'day' | 'month' | 'year'): string => parts.find((p) => p.type === type)?.value ?? '';
  return `${part('day')}/${part('month')}/${part('year')}`;
}

/** hh:mm in Saigon time (A03's log). */
export function clockText(iso: string): string {
  return new Date(iso).toLocaleTimeString('vi-VN', { hour: '2-digit', minute: '2-digit', hour12: false, timeZone: 'Asia/Ho_Chi_Minh' });
}
