const WORKSPACE_TEXT: Record<Locale, Record<WorkspaceMessageKey, string>> = { vi: workspaceVi, en: workspaceEn };

export function useWorkspaceText(): { t: ScreenTranslate<WorkspaceMessageKey>; locale: Locale } {
  return useScreenText(WORKSPACE_TEXT);
}

export function roleLabel(t: ScreenTranslate<WorkspaceMessageKey>, role: WorkspaceRole): string {
  return t(`ws.role.${role}`);
}

function isMessageKey(key: string): key is WorkspaceMessageKey {
  return Object.hasOwn(workspaceVi, key);
}

/** The message of an audit action, when this page knows it. */
export function auditKey(action: string): WorkspaceMessageKey | null {
  const key = `ws.audit.${action}`;
  return isMessageKey(key) ? key : null;
}
