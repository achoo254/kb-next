/** Why the server refused a draft, by API error code; any other reads as `other`. */
const SYNC_REASON: Readonly<Record<string, OfficeMessageKey>> = {
  'too-large': 'sync.reason.too-large',
  'no-access': 'sync.reason.no-access',
  'not-found': 'sync.reason.not-found',
  'not-editable': 'sync.reason.not-editable',
};

export function syncReasonKey(code: string | null): OfficeMessageKey {
  return (code ? SYNC_REASON[code] : undefined) ?? 'sync.reason.other';
}

/** "48 KB", "3,2 MB" (a decimal comma in Vietnamese, as the boards write it). */
export function fileSize(locale: Locale, bytes: number): string {
  if (bytes < 1024 * 1024) return `${Math.max(1, Math.round(bytes / 1024))} KB`;
  return `${(bytes / (1024 * 1024)).toLocaleString(locale === 'vi' ? 'vi-VN' : 'en-GB', { maximumFractionDigits: 1 })} MB`;
}

/** The time of day in Saigon, as the boards write it ("21:05"). */
export function clockTime(at: string | number): string {
  return new Date(at).toLocaleTimeString('vi-VN', { hour: '2-digit', minute: '2-digit', timeZone: 'Asia/Ho_Chi_Minh' });
}
