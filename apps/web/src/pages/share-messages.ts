const SHARE_TEXT: Record<Locale, Record<ShareMessageKey, string>> = { vi: shareVi, en: shareEn };

export function useShareText(): { t: ScreenTranslate<ShareMessageKey>; locale: Locale } {
  return useScreenText(SHARE_TEXT);
}

const ZONE = 'Asia/Ho_Chi_Minh';

function dayOf(date: Date): string {
  return new Intl.DateTimeFormat('en-CA', { timeZone: ZONE, year: 'numeric', month: '2-digit', day: '2-digit' }).format(date);
}

/** "21:12" on the day of `now`, else "03/11 21:12". */
export function shareTime(locale: Locale, iso: string, now: Date): string {
  const at = new Date(iso);
  const time = new Intl.DateTimeFormat(locale === 'vi' ? 'vi-VN' : 'en-GB', { timeZone: ZONE, hour: '2-digit', minute: '2-digit', hour12: false }).format(at);
  if (dayOf(at) === dayOf(now)) return time;
  const day = new Intl.DateTimeFormat('en-GB', { timeZone: ZONE, day: '2-digit', month: '2-digit' }).format(at);
  return `${day} ${time}`;
}

/** "03/11/2026" (an expiry date). */
export function shareDate(iso: string): string {
  return new Intl.DateTimeFormat('en-GB', { timeZone: ZONE, day: '2-digit', month: '2-digit', year: 'numeric' }).format(new Date(iso));
}

/** Whether `iso` falls on the day of `now` (Saigon). */
export function isToday(iso: string, now: Date): boolean {
  return dayOf(new Date(iso)) === dayOf(now);
}
